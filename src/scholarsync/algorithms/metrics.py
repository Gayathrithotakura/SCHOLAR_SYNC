"""Evaluation metrics and statistical analysis for academic schedules."""

import math
from dataclasses import dataclass
from datetime import timedelta

from scholarsync.models.schedule import ScheduleResult
from scholarsync.models.student import StudentProfile


@dataclass(frozen=True)
class ScheduleMetrics:
    """Quantitative performance metrics for an academic schedule.

    Attributes:
        total_tasks: Total number of tasks considered.
        completed_tasks: Number of tasks completely scheduled.
        completion_rate: Ratio of completed tasks to total tasks (0.0 to 1.0).
        on_time_tasks: Number of tasks completed on or before deadline.
        on_time_rate: Ratio of on-time completions (0.0 to 1.0).
        total_scheduled_hours: Sum of all scheduled study hours.
        total_available_hours: Sum of student available hours within the planning horizon.
        capacity_utilization: Ratio of scheduled study hours to available capacity (0.0 to 1.0).
        mean_daily_hours: Average study hours per active day.
        std_daily_hours: Standard deviation of daily study hours (workload balance).
        high_difficulty_hours: Total hours allocated to high/very hard tasks (Difficulty >= 4).
        cognitive_load_index: Composite cognitive tax (sum of task difficulty x hours).
    """

    total_tasks: int
    completed_tasks: int
    completion_rate: float
    on_time_tasks: int
    on_time_rate: float
    total_scheduled_hours: float
    total_available_hours: float
    capacity_utilization: float
    mean_daily_hours: float
    std_daily_hours: float
    high_difficulty_hours: float
    cognitive_load_index: float


def evaluate_schedule(result: ScheduleResult, student: StudentProfile) -> ScheduleMetrics:
    """Compute comprehensive performance and cognitive metrics for a ScheduleResult.

    Args:
        result: The ScheduleResult generated by a scheduling strategy.
        student: The StudentProfile providing daily availability limits.

    Returns:
        ScheduleMetrics containing completion rates, capacity utilization, and workload variance.
    """
    total_tasks_count = len(result.completed_tasks) + len(result.unscheduled_tasks)
    completed_count = len(result.completed_tasks)

    completion_rate = (
        round(completed_count / total_tasks_count, 4) if total_tasks_count > 0 else 1.0
    )

    # Check on-time completions
    on_time_count = 0
    for task in result.completed_tasks:
        finish_date = result.task_completion_dates.get(task.task_id)
        if finish_date is not None and finish_date <= task.deadline:
            on_time_count += 1

    on_time_rate = round(on_time_count / total_tasks_count, 4) if total_tasks_count > 0 else 1.0

    # Calculate total available hours in horizon
    total_avail = 0.0
    curr_date = result.start_date
    while curr_date <= result.end_date:
        weekday_name = curr_date.strftime("%A").lower()
        total_avail += student.get_daily_hours(weekday_name)
        curr_date += timedelta(days=1)

    capacity_util = (
        round(result.total_scheduled_hours / total_avail, 4) if total_avail > 0.0 else 0.0
    )

    # Compute daily distribution metrics across the horizon
    daily_hours_list: list[float] = []
    curr_date = result.start_date
    while curr_date <= result.end_date:
        day_h = result.daily_allocated_hours(curr_date)
        if day_h > 0.0:
            daily_hours_list.append(day_h)
        curr_date += timedelta(days=1)

    active_days_count = len(daily_hours_list)
    if active_days_count > 0:
        mean_hours = sum(daily_hours_list) / active_days_count
        variance = sum((h - mean_hours) ** 2 for h in daily_hours_list) / active_days_count
        std_hours = math.sqrt(variance)
    else:
        mean_hours = 0.0
        std_hours = 0.0

    # Cognitive load metrics
    high_diff_hours = 0.0
    cognitive_index = 0.0

    # Map task difficulty by task_id
    all_tasks = result.completed_tasks + result.unscheduled_tasks
    task_difficulty_map = {t.task_id: t.difficulty for t in all_tasks}

    for session in result.sessions:
        diff = task_difficulty_map.get(session.task_id, 3)
        if diff >= 4:
            high_diff_hours += session.hours
        cognitive_index += diff * session.hours

    return ScheduleMetrics(
        total_tasks=total_tasks_count,
        completed_tasks=completed_count,
        completion_rate=completion_rate,
        on_time_tasks=on_time_count,
        on_time_rate=on_time_rate,
        total_scheduled_hours=round(result.total_scheduled_hours, 2),
        total_available_hours=round(total_avail, 2),
        capacity_utilization=min(1.0, capacity_util),
        mean_daily_hours=round(mean_hours, 2),
        std_daily_hours=round(std_hours, 2),
        high_difficulty_hours=round(high_diff_hours, 2),
        cognitive_load_index=round(cognitive_index, 2),
    )
